-- V1: initial schema. Must stay in sync with the JPA entities (Hibernate runs in `validate` mode when this is active).
-- Statements are idempotent (IF NOT EXISTS) so a database first created by Hibernate's ddl-auto=update
-- can be adopted by Flyway's baseline-on-migrate without a manual step.

create table if not exists short_links (
    id                  bigint generated by default as identity primary key,
    code                varchar(32)   not null,
    original_url        varchar(2048) not null,
    created_at          timestamp(6) with time zone not null,
    expires_at          timestamp(6) with time zone,
    active              boolean       not null,
    click_count         bigint        not null,
    idempotency_key     varchar(64),
    request_fingerprint varchar(64),
    constraint uk_short_links_code unique (code),
    constraint uk_short_links_idempotency_key unique (idempotency_key)
);

create table if not exists click_events (
    id            bigint generated by default as identity primary key,
    code          varchar(32)  not null,
    clicked_at    timestamp(6) with time zone not null,
    click_day     date         not null,
    referrer_host varchar(255) not null,
    visitor_hash  varchar(32)  not null
);

create index if not exists idx_click_code_day     on click_events (code, click_day);
create index if not exists idx_click_code_visitor on click_events (code, visitor_hash);
